// Pure renderers for OS auto-start services (systemd, launchd, Windows Scheduled Tasks).

export const SERVICE_LABELS = {
  web: 'Web Command Center & Express Proxy',
  bot: 'Rust Trading Engine Daemon',
};

export function systemdUnitName(component) {
  return `apexrust-${component}.service`;
}

export function launchdLabel(component) {
  return `com.apexrust.${component}`;
}

export function windowsTaskName(component) {
  return component === 'web' ? 'ApexRust-Web' : 'ApexRust-Bot';
}

/** systemd escapes `%` specifiers; quote paths for ExecStart so spaces are safe. */
function systemdEscape(value) {
  return String(value).replace(/%/g, '%%');
}

export function renderSystemdUnit({ component, repoDir, nodePath, system = false, user, pathEnv }) {
  const exec = `"${systemdEscape(nodePath)}" "${systemdEscape(`${repoDir}/scripts/apexrust.mjs`)}" run ${component}`;
  const lines = [
    '# Generated by ./apexrust service install — do not edit by hand (re-run the installer instead).',
    '[Unit]',
    `Description=ApexRust Quant ${SERVICE_LABELS[component]}`,
    'After=network-online.target',
    'Wants=network-online.target',
    '',
    '[Service]',
    'Type=simple',
    `WorkingDirectory=${systemdEscape(repoDir)}`,
    `ExecStart=${exec}`,
  ];
  if (pathEnv) lines.push(`Environment="PATH=${systemdEscape(pathEnv)}"`);
  lines.push('Restart=on-failure', 'RestartSec=5', 'KillSignal=SIGTERM', 'TimeoutStopSec=20');
  if (system) {
    if (user) lines.push(`User=${user}`);
    lines.push('NoNewPrivileges=true', 'PrivateTmp=true');
  }
  lines.push('', '[Install]', `WantedBy=${system ? 'multi-user.target' : 'default.target'}`, '');
  return lines.join('\n');
}

function xmlEscape(value) {
  return String(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&apos;');
}

export function renderLaunchdPlist({ component, repoDir, nodePath, logPath, pathEnv }) {
  const args = [nodePath, `${repoDir}/scripts/apexrust.mjs`, 'run', component];
  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">',
    '<plist version="1.0">',
    '<dict>',
    '  <key>Label</key>',
    `  <string>${xmlEscape(launchdLabel(component))}</string>`,
    '  <key>ProgramArguments</key>',
    '  <array>',
    ...args.map((a) => `    <string>${xmlEscape(a)}</string>`),
    '  </array>',
    '  <key>WorkingDirectory</key>',
    `  <string>${xmlEscape(repoDir)}</string>`,
    '  <key>EnvironmentVariables</key>',
    '  <dict>',
    '    <key>PATH</key>',
    `    <string>${xmlEscape(pathEnv ?? '/usr/local/bin:/opt/homebrew/bin:/usr/bin:/bin')}</string>`,
    '  </dict>',
    '  <key>RunAtLoad</key>',
    '  <true/>',
    '  <key>KeepAlive</key>',
    '  <dict>',
    '    <key>SuccessfulExit</key>',
    '    <false/>',
    '  </dict>',
    '  <key>ThrottleInterval</key>',
    '  <integer>10</integer>',
    '  <key>StandardOutPath</key>',
    `  <string>${xmlEscape(logPath)}</string>`,
    '  <key>StandardErrorPath</key>',
    `  <string>${xmlEscape(logPath)}</string>`,
    '</dict>',
    '</plist>',
    '',
  ].join('\n');
}

/** PowerShell single-quoted string literal. */
function psQuote(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

/**
 * PowerShell script registering a per-user logon Scheduled Task (no admin required).
 * The task runs a hidden PowerShell that launches `node scripts/apexrust.mjs run <component> --log <file>`.
 */
export function renderWindowsTaskScript({ component, repoDir, nodePath, logPath }) {
  const cli = `${repoDir}\\scripts\\apexrust.mjs`;
  // Inner command executed by the hidden PowerShell host
  const inner = `& ${psQuote(nodePath)} ${psQuote(cli)} run ${component} --log ${psQuote(logPath)}`;
  const argument = `-NoProfile -NonInteractive -WindowStyle Hidden -ExecutionPolicy Bypass -Command "${inner.replace(/"/g, '\\"')}"`;
  return [
    "$ErrorActionPreference = 'Stop'",
    `$action = New-ScheduledTaskAction -Execute 'powershell.exe' -Argument ${psQuote(argument)} -WorkingDirectory ${psQuote(repoDir)}`,
    '$trigger = New-ScheduledTaskTrigger -AtLogOn -User $env:USERNAME',
    '$settings = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -StartWhenAvailable -RestartCount 5 -RestartInterval (New-TimeSpan -Minutes 1) -ExecutionTimeLimit ([TimeSpan]::Zero) -MultipleInstances IgnoreNew',
    '$principal = New-ScheduledTaskPrincipal -UserId $env:USERNAME -LogonType Interactive -RunLevel Limited',
    `Register-ScheduledTask -TaskName ${psQuote(windowsTaskName(component))} -Description ${psQuote(`ApexRust Quant ${SERVICE_LABELS[component]}`)} -Action $action -Trigger $trigger -Settings $settings -Principal $principal -Force | Out-Null`,
    '',
  ].join('\n');
}
